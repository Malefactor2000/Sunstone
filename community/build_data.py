"""Everyone's shares -> the addon's CommunityData.lua (and the desktop helper's data/community.json).

    venv\\Scripts\\python.exe tools\\community\\build_data.py <folder of shares> [--players-needed 3] [--out CommunityData.lua]

The folder holds one .json per sender (tools/community/pull.py puts them there). Every share is cleaned and the outliers
thrown out by app/share.py; what nobody else confirms stays out, except a pet's or mount's source, which the addon
shows as "not confirmed". Prints what's new, so names of creatures can be looked over before a release."""
import argparse
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, "app"))
import share  # noqa: E402


def num(v):
    s = f"{v:.4g}" if isinstance(v, float) and v != int(v) else str(int(v))
    return s


def lua(v):
    if isinstance(v, (int, float)):
        return num(v)
    if isinstance(v, str):
        return '"' + v.replace("\\", "").replace('"', "") + '"'
    if isinstance(v, (list, tuple)):
        return "{" + ",".join(lua(x) for x in v) + "}"
    return "{" + ",".join(f"[{k if not isinstance(k, str) else json.dumps(k)}]={lua(x)}" for k, x in sorted(v.items(), key=lambda kv: str(kv[0]))) + "}"


def spots(cells):
    out = []
    for c in cells:
        m, r = divmod(c, 10000)
        out += [m, r // 100 + 0.5, r % 100 + 0.5]
    return out


def build(folder, need=3):
    shares = {}
    for name in sorted(os.listdir(folder)):
        if not name.lower().endswith((".json", ".txt")):
            continue
        with open(os.path.join(folder, name), encoding="utf-8", errors="replace") as f:
            d = share.read_code(f.read())
        if d:
            shares[d.get("id") or name] = d  # one per sender
    data = share.merge(list(shares.values()), need)
    fx = data["fx"]
    mobs = {}
    for npc, m in data["mobs"].items():
        l = m["l"]
        if l >= 20:
            items = []
            for i, n in sorted(m["i"].items(), key=lambda x: -x[1])[:30]:
                items += [int(i), round(n / l, 4)]
            e = {"l": l, "n": m["reports"], "c": round(m["c"] / l, 2), "i": items}
            for f in ("lo", "hi"):
                if f in m:
                    e[f] = m[f]
            mobs[int(npc)] = e
    pace = {}
    for lv, b in (data["ctx"].get("solo") or {}).items():
        if b["k"] >= 20:
            pace[int(lv)] = [round(b["t"]), b["k"]]

    def opened(kind):
        o = {}
        for i, e in fx[kind].items():
            row = {"n": e["n"], "p": e["p"], "i": [x for iid, n in sorted(e["i"].items(), key=lambda z: -z[1])[:30] for x in (iid, n)]}
            if e.get("at"):
                row["at"] = spots(e["at"])
            o[i] = row
        return o
    out = {
        "players": len(shares), "built": time.strftime("%Y-%m-%d"), "mobs": mobs,
        "at": {npc: spots(e["c"]) for npc, e in fx["at"].items() if e["p"] >= 2}, "names": fx["nm"],
        "obj": opened("obj"), "box": opened("box"), "fish": opened("fish"), "qi": fx["qi"],
        "vend": {int(npc): [x for i, e in v["i"].items() if e["c"] > 0 and not e.get("x") for x in (int(i), e["c"], e["n"])] for npc, v in data["vend"].items()},
        "src": {i: [x for r in rows for x in r] for i, rows in fx["src"].items()}, "pace": pace, "xp": fx["xp"], "kt": fx["kt"],
    }
    out["vend"] = {k: v for k, v in out["vend"].items() if v}
    return out, data, len(shares)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("folder")
    ap.add_argument("--players-needed", type=int, default=3)
    ap.add_argument("--out", default=os.path.join(ROOT, "work", "Sunstone", "CommunityData.lua"))
    ap.add_argument("--json", default=os.path.join(ROOT, "data", "community.json"))
    a = ap.parse_args()
    out, data, n = build(a.folder, a.players_needed)
    body = ",\n".join(f"{k}={lua(v)}" for k, v in out.items())
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- Sunstone: everyone's numbers. GENERATED by tools/community/build_data.py from what players shared: do not edit by hand.\n"
                "SunstoneCommunity = {\n" + body + "\n}\n")
    os.makedirs(os.path.dirname(a.json), exist_ok=True)
    with open(a.json, "w", encoding="utf-8") as f:
        json.dump(data, f, separators=(",", ":"))
    print(f"{n} senders: {len(out['mobs'])} creatures, {len(out['at'])} with places, {len(out['vend'])} vendors, {len(out['obj'])} chests, "
          f"{len(out['box'])} crates, {len(out['src'])} pets/mounts with sources, XP at {len(out['xp'])} levels")
    if out["names"]:
        print("names to look over:", ", ".join(f"{k} {v}" for k, v in sorted(out["names"].items())))


if __name__ == "__main__":
    main()
